        SALE_PRICE,
        DISCOUNT_AMT,
        COUPON_AMT,
        NET_PAID,
        NET_PAID_TAX,
        NET_PROFIT
    )
    SELECT
        CO.ORDER_DATE,
        CD.CUSTOMER_DIM_KEY,
        ID.ITEM_DIM_KEY,
        COUNT(1) AS ORDER_COUNT,
        SUM(CO.ORDER_QUANTITY),
        SUM(CO.SALE_PRICE),
        SUM(CO.DISCOUNT_AMT),
        SUM(CO.COUPON_AMT),
        SUM(CO.NET_PAID),
        SUM(CO.NET_PAID_TAX),
        SUM(CO.NET_PROFIT)
    FROM
        CURATED_ZONE.CURATED_ORDER CO
        JOIN CONSUMPTION_ZONE.CUSTOMER_DIM CD ON CD.CUSTOMER_ID = CO.CUSTOMER_ID
        JOIN CONSUMPTION_ZONE.ITEM_DIM ID ON ID.ITEM_ID = CO.ITEM_ID
        AND ID.ITEM_DESC = CO.ITEM_DESC
        AND ID.END_DATE IS NOT NULL
    GROUP BY
        CO.ORDER_DATE,
        CD.CUSTOMER_DIM_KEY,
        ID.ITEM_DIM_KEY
    ORDER BY CO.ORDER_DATE;



