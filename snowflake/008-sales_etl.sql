CREATE OR REPLACE TASK ETL.CONSUMPTION_ZONE.ITEM_CONSUMPTION_TASK
    WAREHOUSE = 'DATA_ENGINEER_WH'
    SCHEDULE = '4 Minute'
    WHEN SYSTEM$STREAM_HAS_DATA('ETL.CURATED_ZONE.CUR_ITEM_STREAM')
    AS
    MERGE INTO ETL.CONSUMPTION_ZONE.ITEM_DIM ITEM USING ETL.CURATED_ZONE.CUR_ITEM_STREAM ITEM_STREAM
    ON ITEM.ITEM_ID = ITEM_STREAM.ITEM_ID
    AND ITEM.START_DATE = ITEM_STREAM.START_DATE
    AND ITEM.ITEM_DESC = ITEM_STREAM.ITEM_DESC
    WHEN MATCHED
        AND ITEM_STREAM.METADATA$ACTION = 'INSERT'
        AND ITEM_STREAM.METADATA$ISUPDATE = 'TRUE' THEN
        UPDATE SET
            ITEM.END_DATE = ITEM_STREAM.END_DATE,
            ITEM.PRICE = ITEM_STREAM.PRICE,
            ITEM.ITEM_CLASS = ITEM_STREAM.ITEM_CLASS,
            ITEM.ITEM_CATEGORY = ITEM_STREAM.ITEM_CATEGORY
    
    WHEN MATCHED
        AND ITEM_STREAM.METADATA$ACTION = 'DELETE'
        AND ITEM_STREAM.METADATA$ISUPDATE = 'FALSE' THEN
        UPDATE
        SET
            ITEM.ACTIVE_FLAG = 'N',
            UPDATED_TIMESTAMP = CURRENT_TIMESTAMP()
    
    WHEN NOT MATCHED
        AND ITEM_STREAM.METADATA$ACTION = 'INSERT'
        AND ITEM_STREAM.METADATA$ISUPDATE = 'FALSE' THEN
        INSERT(
            ITEM_ID,
            ITEM_DESC,
            START_DATE,
            END_DATE,
            PRICE,
            ITEM_CLASS,
            ITEM_CATEGORY
        )
        VALUES(
            ITEM_STREAM.ITEM_ID,
            ITEM_STREAM.ITEM_DESC,
            ITEM_STREAM.START_DATE,
            ITEM_STREAM.END_DATE,
            ITEM_STREAM.PRICE,
            ITEM_STREAM.ITEM_CLASS,
            ITEM_STREAM.ITEM_CATEGORY
        );


