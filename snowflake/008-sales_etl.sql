CREATE OR REPLACE TASK ETL.CURATED_ZONE.CURATED_ITEM_TASK
    WAREHOUSE = 'DATA_ENGINEER_WH'
    SCHEDULE = '3 Minute'
    WHEN SYSTEM$STREAM_HAS_DATA('ETL.LANDING_ZONE.ITEM_STREAM')
    AS
    MERGE INTO ETL.CURATED_ZONE.CURATED_ITEM CUR_ITEM USING ETL.LANDING_ZONE.ITEM_STREAM RAW_ITEM
    ON CUR_ITEM.ITEM_ID = RAW_ITEM.ITEM_ID
    AND CUR_ITEM.ITEM_DESC = RAW_ITEM.ITEM_DESC
    AND CUR_ITEM.START_DATE = RAW_ITEM.START_DATE
    WHEN MATCHED
        THEN UPDATE SET
            CUR_ITEM.END_DATE = RAW_ITEM.END_DATE,
            CUR_ITEM.PRICE = RAW_ITEM.PRICE,
            CUR_ITEM.ITEM_CLASS = RAW_ITEM.ITEM_CLASS,
            CUR_ITEM.ITEM_CATEGORY = RAW_ITEM.ITEM_CATEGORY
    WHEN NOT MATCHED
        THEN
            INSERT(ITEM_ID, ITEM_DESC, START_DATE, END_DATE, PRICE, ITEM_CLASS, ITEM_CATEGORY)
            VALUES(RAW_ITEM.ITEM_ID, RAW_ITEM.ITEM_DESC, RAW_ITEM.START_DATE, RAW_ITEM.END_DATE, RAW_ITEM.PRICE, RAW_ITEM.ITEM_CLASS, RAW_ITEM.ITEM_CATEGORY);

