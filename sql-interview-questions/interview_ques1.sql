-- Total Purchases by each customers
WITH RES AS(
    SELECT
        CUST_ID,
        COUNT(*) AS CNT
    FROM
        ORD
    GROUP BY CUST_ID
)
SELECT
    CUST.CUST_ID,
    CUST.NAME,
    RES.CNT AS TOTAL_PURCHASES
FROM
    CUST
    INNER JOIN RES
    ON RES.CUST_ID = CUST.CUST_ID;

-- Query to get customers who bought anything
SELECT * FROM CUST WHERE CUST_ID IN (SELECT DISTINCT CUST_ID FROM ORD);
SELECT * FROM CUST WHERE EXISTS (SELECT 1 FROM ORD WHERE ORD.CUST_ID = CUST.CUST_ID) ORDER BY CUST.CUST_ID;

-- Query to get the customer who hasn't bought anything
SELECT * FROM CUST WHERE CUST_ID NOT IN (SELECT DISTINCT CUST_ID FROM ORD);
SELECT * FROM CUST WHERE NOT EXISTS (SELECT 1 FROM ORD WHERE ORD.CUST_ID = CUST.CUST_ID) ORDER BY CUST.CUST_ID;

