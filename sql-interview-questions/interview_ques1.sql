-- Query to get missing values using recursive CTEs
SELECT * FROM TMP1;

WITH REC(N) AS(
    SELECT 1 FROM DUAL
    UNION ALL
    SELECT N + 1 FROM REC WHERE N < (SELECT MAX(ID) FROM TMP1)
),
RES AS(
    SELECT
        A.N AS ID_1,
        B.ID AS ID_2
    FROM
        REC A LEFT JOIN TMP1 B ON A.N = B.ID 
)
SELECT
    ID_1 AS ID
FROM RES
WHERE ID_2 IS NULL
ORDER BY ID_1;

