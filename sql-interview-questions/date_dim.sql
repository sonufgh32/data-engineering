    SYSDATE + INTERVAL '24' HOUR AS ADD_HOUR,
    SYSDATE + INTERVAL '1440' MINUTE AS ADD_MINUTE,
    SYSDATE + INTERVAL '86400' SECOND AS ADD_SECOND
