-- Method 1: Query to fund allocation using multiple joins
SELECT
    F.PARTID,
    F.FUNDID,
    F.BALANCE,
    F.BALANCE * A1.ALLOCATION_PERCENTAGE AS BOND,
    F.BALANCE * A2.ALLOCATION_PERCENTAGE AS CASH,
    F.BALANCE * A3.ALLOCATION_PERCENTAGE AS CTSK
FROM
    FUND F
    LEFT JOIN FUND_ALLOCATION A1 ON F.FUNDID = A1.FUNDID AND A1.ALLOCATION_TYPE = 'BOND'
    LEFT JOIN FUND_ALLOCATION A2 ON F.FUNDID = A2.FUNDID AND A2.ALLOCATION_TYPE = 'CASH'
    LEFT JOIN FUND_ALLOCATION A3 ON F.FUNDID = A3.FUNDID AND A3.ALLOCATION_TYPE = 'CTSK';

-- Method 2: Query to fund allocation using conditional aggregation
SELECT
    F.PARTID,
    F.FUNDID,
    F.BALANCE,
    ROUND(SUM(CASE WHEN A.ALLOCATION_TYPE = 'BOND' THEN A.ALLOCATION_PERCENTAGE * F.BALANCE ELSE 0 END), 2) AS BOND,
    ROUND(SUM(CASE WHEN A.ALLOCATION_TYPE = 'CASH' THEN A.ALLOCATION_PERCENTAGE * F.BALANCE ELSE 0 END), 2) AS CASH,
    ROUND(SUM(CASE WHEN A.ALLOCATION_TYPE = 'CTSK' THEN A.ALLOCATION_PERCENTAGE * F.BALANCE ELSE 0 END), 2) AS CTSK
FROM
    FUND F
    LEFT JOIN FUND_ALLOCATION A ON F.FUNDID = A.FUNDID
GROUP BY F.PARTID, F.FUNDID, F.BALANCE;

