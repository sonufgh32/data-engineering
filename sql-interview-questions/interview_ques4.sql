-- Method 1: Query to get total sales by department and percentage contribution
SELECT
    DISTINCT DEPARTMENT_ID,
    SUM(TOTAL_SALES) OVER(PARTITION BY DEPARTMENT_ID) AS DEPARTMENT_TOTAL_SALES,
    ROUND((SUM(TOTAL_SALES) OVER(PARTITION BY DEPARTMENT_ID) / SUM(TOTAL_SALES) OVER()) * 100, 2) AS SALES_PERCENTAGE_BY_DEPARTMENT
FROM SALES;

-- Method 2: Query to get total sales by department and percentage contribution
SELECT
    SALES_ID, EMPLOYEE_NAME, DEPARTMENT_ID, TOTAL_SALES,
    ROUND((TOTAL_SALES / SUM(TOTAL_SALES) OVER()) * 100, 2) AS PERCENTAGE
FROM SALES;

