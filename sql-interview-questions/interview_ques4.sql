SELECT * FROM SALARY ORDER BY TENURE;

WITH SAL AS (
    SELECT
        TENURE,
        SALARY,
        NTH_VALUE(SALARY, 2) OVER(PARTITION BY TENURE ORDER BY SALARY DESC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS VAL_0,
        NTH_VALUE(SALARY, 2) OVER(PARTITION BY TENURE ORDER BY SALARY DESC) AS VAL
    FROM SALARY
) SELECT * FROM SAL WHERE VAL IS NOT NULL;

-- Query to get the 2nd lowest salary for each tenure
WITH SAL AS (
    SELECT
        TENURE,
        SALARY,
        DENSE_RANK() OVER(PARTITION BY TENURE ORDER BY SALARY ASC) AS DN
    FROM
        SALARY
)
SELECT TENURE, SALARY, DN FROM SAL WHERE DN = 2;

-- Query to get the 2nd highest salary for each tenure, if not available get the highest salary
WITH SAL AS (
    SELECT
        TENURE,
        SALARY,
        DENSE_RANK() OVER(PARTITION BY TENURE ORDER BY SALARY DESC) AS DN
    FROM SALARY
), SECOND AS(
    SELECT * FROM SAL WHERE DN = 2
), FIRST AS (
    SELECT
        *
    FROM
        SAL
    WHERE
        TENURE NOT IN (SELECT DISTINCT TENURE FROM SECOND) AND
        DN = 1
), RES AS(
    SELECT TENURE, SALARY FROM FIRST
    UNION
    SELECT TENURE, SALARY FROM SECOND
) SELECT * FROM RES ORDER BY TENURE;


