-- Method 1: Query to get count of days stock price increased by more than 5%
WITH RES AS(
    SELECT
        STOCK,
        (CLOSE_PRICE - OPEN_PRICE) / OPEN_PRICE AS PER
    FROM STOCK_PRICES
)
SELECT
    STOCK,
    COUNT(*) CNT
FROM
    RES
WHERE PER > 0.05
GROUP BY STOCK;

