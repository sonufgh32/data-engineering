-- UPDATE DEPARTMENT NAMES BASED ON DEPTNO

SELECT * FROM EMP_INT;

UPDATE EMP_INT 
SET
DEPT_NAME = (
    CASE
        WHEN DEPTNO = 10
            THEN 'ENGINEERING'
        WHEN DEPTNO = 20
            THEN 'SALES'
        ELSE 'HR'
    END
);

