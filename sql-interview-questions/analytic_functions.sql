WITH TOTALS AS (
    SELECT
        B.*,
        SUM(WEIGHT) OVER(
            PARTITION BY SHAPE
        ) WEIGHT_PER_SHAPE,
        SUM(WEIGHT) OVER(
            PARTITION BY SHAPE
            ORDER BY BRICK_ID
        ) RUNNING_WEIGHT_BY_ID
    FROM BRICKS B
)
SELECT
    *
FROM TOTALS
WHERE
    WEIGHT_PER_SHAPE > 4
    AND RUNNING_WEIGHT_BY_ID > 4
ORDER BY BRICK_ID;

SELECT
    B.*,
    COUNT(*) OVER(
        ORDER BY WEIGHT
    ) AS RUNNING_TOTAL,
    SUM(WEIGHT) OVER(
        ORDER BY WEIGHT
    ) RUNNING_WEIGHT
FROM
    BRICKS B
ORDER BY WEIGHT;

SELECT
    B.*,
    COUNT(*) OVER(
        ORDER BY WEIGHT
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) RUNNING_TOTAL,
    SUM(WEIGHT) OVER(
        ORDER BY WEIGHT
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) RUNNING_WEIGHT
FROM
    BRICKS B
ORDER BY WEIGHT;

SELECT
    B.*,
    COUNT(*) OVER(
        ORDER BY WEIGHT, BRICK_ID
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) RUNNING_TOTAL,
    SUM(WEIGHT) OVER(
        ORDER BY WEIGHT, BRICK_ID
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) RUNNING_WEIGHT
FROM
    BRICKS B
ORDER BY WEIGHT, BRICK_ID;

SELECT
    B.*,
    SUM(WEIGHT) OVER(
        ORDER BY WEIGHT
        ROWS BETWEEN 1 PRECEDING AND CURRENT ROW
    ) RUNNING_ROW_WEIGHT,
    SUM(WEIGHT) OVER(
        ORDER BY WEIGHT
        RANGE BETWEEN 1 PRECEDING AND CURRENT ROW
    ) RUNNING_VALUE_WEIGHT
FROM
    BRICKS B 
ORDER BY WEIGHT, BRICK_ID;