SELECT COUNT(*) FROM BRICKS;

SELECT COUNT(1) OVER() AS TOTAL_COUNT FROM BRICKS;

SELECT B.*, COUNT(1) OVER() AS TOTAL_COUNT FROM BRICKS B;

SELECT B.*, COUNT(1) OVER(ORDER BY BRICK_ID) AS TOTAL_COUNT FROM BRICKS B;

SELECT B.*, COUNT(1) OVER(ORDER BY COLOUR) AS TOTAL_COUNT FROM BRICKS B;

SELECT
    B.*,
    ROW_NUMBER() OVER(PARTITION BY COLOUR ORDER BY SHAPE) AS RN,
    RANK() OVER(PARTITION BY COLOUR ORDER BY SHAPE) AS RANK,
    DENSE_RANK() OVER(PARTITION BY COLOUR ORDER BY SHAPE) AS DENSE_RANK
FROM
    BRICKS B;


-- Note: In some databases rank() / dense_rank() with over() return 1 for each rows

SELECT
    DISTINCT WEIGHT,
    COUNT(*) OVER(PARTITION by WEIGHT) AS WEIGHT_COUNT
FROM
    BRICKS b ORDER BY WEIGHT DESC;

SELECT COLOUR, COUNT(1), SUM(weight) FROM BRICKS GROUP BY COLOUR;

SELECT
    B.*,
    COUNT(*) OVER(PARTITION BY COLOUR) COUNT_PER_COLOUR,
    SUM(WEIGHT) OVER(PARTITION BY COLOUR) WEIGHT_PER_COLOUR
FROM BRICKS B;

SELECT
    B.*,
    COUNT(*) OVER(PARTITION BY SHAPE) BRICKS_PER_SHAPE,
    MEDIAN(WEIGHT) OVER(PARTITION BY SHAPE) MEDIAN_WEIGHT_PER_SHAPE
FROM
    BRICKS B
    ORDER BY SHAPE, WEIGHT, BRICK_ID;

SELECT
    B.*,
    COUNT(*) OVER(ORDER BY BRICK_ID) RUNNING_TOTAL,
    SUM(WEIGHT) OVER(ORDER BY BRICK_ID) RUNNING_WEIGHT
FROM BRICKS B;

SELECT
    B.BRICK_ID,
    B.WEIGHT,
    ROUND(AVG(WEIGHT) OVER(ORDER BY BRICK_ID), 2) AS AVERAGE_RUNNING_WEIGHT
FROM BRICKS B;

SELECT
    B.*,
    COUNT(*) OVER(PARTITION BY COLOUR ORDER BY BRICK_ID) RUNNING_TOTAL,
    SUM(WEIGHT) OVER(PARTITION BY COLOUR ORDER BY BRICK_ID) RUNNING_WEIGHT
FROM BRICKS B;

SELECT
    B.*,
    FIRST_VALUE(WEIGHT) OVER(ORDER BY BRICK_ID) AS FIRST_WEIGHT_BY_ID,
    LAST_VALUE(WEIGHT) OVER(ORDER BY BRICK_ID) AS LAST_WEIGHT_BY_ID
FROM BRICKS B;

SELECT
    B.*,
    FIRST_VALUE(WEIGHT) OVER(PARTITION BY SHAPE) AS FIRST_WEIGHT_SHAPE_PARTITION,
    LAST_VALUE(WEIGHT) OVER(PARTITION BY SHAPE) AS LAST_WEIGHT_SHAPE_PARTITION,
    NTH_VALUE(WEIGHT, 2) OVER(PARTITION BY SHAPE ORDER BY COLOUR) AS NTH_WEIGHT_SHAPE_PARTITION
FROM BRICKS B;

SELECT
    B.*,
    FIRST_VALUE(WEIGHT) OVER(PARTITION BY SHAPE ORDER BY BRICK_ID) AS FIRST_WEIGHT_SHAPE_PARTITION,
    LAST_VALUE(WEIGHT) OVER(PARTITION BY SHAPE ORDER BY BRICK_ID) AS LAST_WEIGHT_SHAPE_PARTITION -- RUNNING VALUES
FROM BRICKS B;

SELECT
    B.*,
    LAG(SHAPE) OVER(ORDER BY BRICK_ID) PREV_SHAPE,
    LEAD(SHAPE) OVER(ORDER BY BRICK_ID) NEXT_SHAPE
FROM BRICKS B;

SELECT
    B.*,
    NVL(LAG(SHAPE) OVER(ORDER BY BRICK_ID), SHAPE) PREV_SHAPE,
    NVL(LEAD(SHAPE) OVER(ORDER BY BRICK_ID), SHAPE) NEXT_SHAPE
FROM BRICKS B;

-- FILTERING FUNCTIONS

SELECT
    COLOUR
FROM BRICKS
GROUP BY COLOUR
HAVING COUNT(*) >= 2;

